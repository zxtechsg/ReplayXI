#!/usr/bin/env python3
"""Package the independently verified cycle150 slow-run clip, without a rig.

Uses Python's standard library only. The full probe was generated by
build_replayxi_slow_run_probe.py using the unchanged canonical sampler. This
step checks that fixture, the unchanged base motion, the pinned original FBX
and its Git blob identity before extracting only the run clip. No downloads,
conversion, phase shift, root-path changes or licence removal occur here.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "ReplayXI/Resources/Players/ReplayXIRocketboxMotion.json"
FIXTURE = ROOT / "ReplayXITests/Fixtures/Generated/ReplayXIRocketboxSlowRun150.json"
OUTPUT = ROOT / "ReplayXI/Resources/Players/ReplayXIRocketboxSlowRun.json"
BASE_SHA256 = "d30a7379b81a4b0ea3fef5ebd20ad101911ab4fd521a5be1f6c00c0804f59ce4"
FIXTURE_SHA256 = "81633d787043a30cff0b86ef5272542522d619b7bc9186c7105d75a489bf3062"
SOURCE_SHA256 = "56af7ac64b05653d40f64205b58b2bf915646ee70dd6e2a68bc4536d71f07c1c"
SOURCE_GIT_BLOB = "9ed8f785c6263bac000ea34caec497a1d6c36128"
SOURCE_BYTES = 877200
SOURCE_COMMIT = "0943055db6ec570bcef9f2c8b41c9e5467c808f9"
SOURCE_PATH = "Assets/Animations/all_animations_max_motextr_xy/m_run_slow_01.max.fbx"


def verified(path: Path, digest: str) -> bytes:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"Pinned SHA256 mismatch: {path}")
    return data


def build(source_fbx: Path, output: Path) -> dict:
    source = verified(source_fbx, SOURCE_SHA256)
    blob = hashlib.sha1(b"blob " + str(len(source)).encode() + b"\0" + source).hexdigest()
    if len(source) != SOURCE_BYTES or blob != SOURCE_GIT_BLOB:
        raise ValueError("Pinned FBX byte count or Git blob identity changed")
    base = json.loads(verified(BASE, BASE_SHA256))
    fixture = json.loads(verified(FIXTURE, FIXTURE_SHA256))
    base_run = next(clip for clip in base["clips"] if clip["id"] == "run")
    slow_run = next(clip for clip in fixture["clips"] if clip["id"] == "run")
    control = copy.deepcopy(fixture)
    control["clips"] = [base_run if clip["id"] == "run" else clip for clip in control["clips"]]
    if control != base or base["sourceCommit"] != SOURCE_COMMIT or len(base["joints"]) != 80:
        raise ValueError("Fixture no longer preserves the entire base contract")
    if len(slow_run["frames"]) != 24 or slow_run["durationSeconds"] != 0.7666666507720947:
        raise ValueError("Source duration or closing sample changed")
    notice = (ROOT / "ReplayXI/Resources/Players/LICENSE-ROCKETBOX-MIT.txt").read_text()
    if not notice.startswith("MIT License\n\nCopyright (c) 2020 Microsoft\n"):
        raise ValueError("Expected upstream MIT notice is missing")
    package = {
        "schemaVersion": 1, "baseMotionSHA256": BASE_SHA256,
        "sourceCommit": SOURCE_COMMIT, "sourceClipSHA256": SOURCE_SHA256,
        "sourcePath": SOURCE_PATH, "sourceBytes": SOURCE_BYTES,
        "sourceGitBlobSHA1": SOURCE_GIT_BLOB,
        "jointCount": 80, "units": "metres", "phaseOffsetRadians": 0,
        "license": notice, "clip": slow_run,
    }
    payload = (json.dumps(package, separators=(",", ":"), allow_nan=False) + "\n").encode()
    # This builder cannot overwrite the base, licence, fixture or source inputs.
    if output.resolve() in {BASE.resolve(), FIXTURE.resolve(), source_fbx.resolve()} or output.suffix != ".json":
        raise ValueError("Expected a separate supplemental JSON destination")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(payload)
    return {"output": str(output), "bytes": len(payload),
            "sha256": hashlib.sha256(payload).hexdigest(),
            "baseMotionSHA256": BASE_SHA256, "sourceClipSHA256": SOURCE_SHA256,
            "sourceGitBlobSHA1": blob, "jointCount": 80, "frames": 24,
            "scope": "Only an unshifted run clip; no duplicate rest, idle, geometry or contacts"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-fbx", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    print(json.dumps(build(args.source_fbx, args.output), indent=2))


if __name__ == "__main__":
    main()
